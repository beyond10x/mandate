//! The composition binary, **spawned as a child process**, completing one federated login
//! against an issuer that really signed the proof.
//!
//! # What is different here, and why the file exists
//!
//! Every case in `tests/serve.rs` builds a [`mandate_control_plane::adapters::Deployment`]
//! in-process and hands it `mandate_federation::verifier::ConstructedVerifier` — a double
//! that performs no cryptography and returns the proof it was constructed with. `src/main.rs`
//! wires `RealVerifier` over `UreqJwks`, which fetches an OIDC discovery document and a JWK
//! Set **over the network** and refuses anything that is not a signed JWT carrying a `kid`
//! that set publishes. No in-process case reaches a byte of that.
//!
//! So this case spawns `target/debug/mandate-control-plane serve` and stands a loopback HTTP
//! issuer beside it: `UreqJwks::admits` (`crates/mandate-federation/src/verifier_real.rs`)
//! admits `http` when the host is loopback, so the issuer needs no TLS. The proof is minted
//! by `mandate_token::signing_real::RealSigner` under a P-256 key generated when the case
//! runs, and the key set the issuer publishes is that signer's own `published_keys()` — so
//! the child verifies a signature made by a key it fetched, and nothing in this file can
//! make it do otherwise.
//!
//! **No key is committed.** The signing key is generated by `aws_lc_rs` on each run; the only
//! key text in this file is the public JWK the `--key` flag publishes, which carries no
//! private member.
//!
//! # The child process
//!
//! [`Served`] owns it. `Drop` kills and reaps on every path — assertion failure, panic, early
//! return — and the wait for the listener is bounded: a child that never binds fails the case
//! with its own stderr rather than hanging.

