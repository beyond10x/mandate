/// The client identifier the IdP issued Mandate, which a proof's `aud` must name.
const IDP_CLIENT: &str = "mandate-at-idp";

/// The `kid` the loopback issuer publishes its signing key under.
const IDP_KID: &str = "idp-key-1";

/// The algorithm the connection is configured to verify under, and the one the proof is
/// signed with. `RealVerifier` compares the header to the connection's configured name and
/// never selects from the header (`../sources/original-design.md:2527`).
const ALGORITHM: &str = "ES256";

/// The issuer identifier the served deployment publishes its own metadata under.
const AS_ISSUER: &str = "https://mandate.example";

const REDIRECT: &str = "https://client.example/callback";

/// The audience the registered resource server holds.
const TARGET_AUDIENCE: &str = "https://api.example";

/// RFC 7636 appendix B's code verifier and the S256 challenge of it.
const VERIFIER: &str = "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk";
const CHALLENGE: &str = "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM";

/// A code verifier in the declared form that is not [`VERIFIER`]: 43 characters, every one
/// of them in RFC 3986's unreserved set, differing in the last.
///
/// Well-formed on purpose. `services/sts/src/redemption.rs:228-241` refuses a malformed
/// verifier as `VerifierMalformed` **before** it digests anything, so a verifier that was
/// merely the wrong shape would drive that refusal and never reach the digest comparison
/// this case exists to drive.
const MISMATCHED_VERIFIER: &str = "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXj";

/// An issuer identifier no connection in this file is configured for.
const FOREIGN_ISSUER: &str = "https://not-the-configured-issuer.example";

/// A client identifier no connection in this file is configured for.
const FOREIGN_CLIENT: &str = "mandate-at-some-other-idp";

/// How far ahead the minted proof's `exp` sits. Well inside `RealVerifier`'s own ceiling on
/// a proof lifetime, which is a day.
const PROOF_TTL: u64 = 300;

/// How long the case waits for the child to bind before failing with its stderr.
const LISTEN_DEADLINE: HostDuration = HostDuration::from_secs(30);

/// A public EC JWK the `--key` flag publishes as the deployment's own key set. Public parts
