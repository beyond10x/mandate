/// Step 5, validate nonce, state and PKCE: a code verifier that does not digest to the
/// recorded challenge.
///
/// The only refusal of the seven that is not answered by the login route. PKCE is redeemed
/// at the token endpoint, so the case walks the accepted road as far as the code and then
/// presents the wrong verifier for it.
#[test]
fn a_code_verifier_that_does_not_match_the_challenge_is_refused_at_step_five() {
    let signer = idp_signer();
    let jwks = serde_json::to_string(&signer.published_keys()).expect("the published key set");
    let issuer = issuer_publishing(jwks);
    let (address, mut served) = stand_up(
        "pkce-mismatch",
        &[ConnectionDocument::accepted(&issuer).rendered()],
    );

    let proof = proof_from(&signer, &issuer, IDP_CLIENT, "proof-pkce");
    let login = login_with(address, connection(), &proof);
    answered("step 5 pkce: POST /v1/federation/login", &login);
    assert_eq!(
        login.status, 200,
        "the login this case builds on is the accepted one; got {} {}",
        login.status, login.body
    );
    let session_proof = member(&login.body, "session_proof");

    let authorize = exchange(
        address,
        &get(
            &format!(
                "/oauth/authorize?response_type=code&client_id={}&redirect_uri={}\
                 &code_challenge={CHALLENGE}&code_challenge_method=S256&state=xyzzy\
                 &nonce=n-0S6&target={}&scope={}",
                client(),
                encoded(REDIRECT),
                resource_server(),
                encoded("read")
            ),
            &[("Authorization", &format!("Bearer {session_proof}"))],
        ),
    );
    answered("step 5 pkce: GET /oauth/authorize", &authorize);
    assert_eq!(
        authorize.status, 302,
        "the authorization this case builds on is the accepted one; got {} {}",
        authorize.status, authorize.body
    );
    let location = authorize
        .header("Location")
        .expect("a Location header")
        .to_owned();
    let (_, query) = location
        .split_once('?')
        .expect("a redirect carrying a query component");
    let code = mandate_proto::oauth::decode_form(query)
        .expect("an x-www-form-urlencoded query")
        .get("code")
        .expect("a code parameter")
        .to_owned();

    // The code the authorization just issued, presented with a verifier that is not the
    // one its challenge was derived from.
    let token = exchange(
        address,
        &post(
            "/oauth/token",
            "application/x-www-form-urlencoded",
            &format!(
                "grant_type=authorization_code&client_id={}&code={}\
                 &code_verifier={MISMATCHED_VERIFIER}&redirect_uri={}",
                client(),
                encoded(&code),
                encoded(REDIRECT)
            ),
            &[],
        ),
    );
    refused(
        "step 5 pkce: POST /oauth/token",
        &token,
        400,
        &grant_refused_body("invalid_grant"),
    );

    // `invalid_grant` is the token endpoint's answer for an expired code, a consumed code,
    // a redirect that does not match and a client that is not the code's, so the body is no
    // more discriminating here than at the login route. The clause is: the presented
    // verifier did not digest to the recorded challenge. The login that got this far
    // refused nothing, so the record names one refusal and it is the redemption's.
    refusal_taken(
        &mut served,
        REDEEM,
        "VerifierMismatch",
        None,
        &[connection()],
    );
}

/// Step 6, validate the configured organization: resolution would be **ambiguous**, and the
/// configuration is refused before a socket rather than every login through it.
///
/// The promise `docs/architecture/federated-login.md` makes on its own — *if tenant
/// resolution is ambiguous, Mandate denies rather than guesses*
/// (`architecture-addendum.md:360`) — is now kept one step earlier than this case used to
/// keep it. `mandate.federation.RegisterFederationConnection` refuses a rule another
/// organization's connection on the same issuer could match for the same proof, and its own
/// comment says why (`crates/mandate-federation/src/record.rs:946-949`): "no command
/// un-registers a connection, so the incumbent could not undo it. Refuse the configuration
/// rather than the logins." Every `--connection` document is run through that command, so
/// this pair never stands a listener up — which is the point: the deployment this case used
/// to build denied the *first* connection's login too, and that login succeeds when its
/// document is the only one given.
///
/// **The login-time clause is not gone and is not covered here.**
/// `DenialClause::TenantAmbiguous` is still reached by a deployment whose folds came from an
/// event log rather than from these flags: `Deployment::record_federation` is the replay
/// path and enforces no command guard, and `register_federation_connection` is a
/// read-then-write guard whose own comment records that storage must enforce it atomically.
/// That case is
/// `tests/serve.rs::two_connections_on_one_issuer_from_a_log_are_still_refused_as_ambiguous`.
///
/// No port is taken and no `PORT` lock is held: the child exits before it binds.
#[test]
fn an_ambiguous_tenant_resolution_is_refused_as_a_configuration_before_the_socket() {
    let signer = idp_signer();
    let jwks = serde_json::to_string(&signer.published_keys()).expect("the published key set");
    let issuer = issuer_publishing(jwks);

    let selected = ConnectionDocument::accepted(&issuer);
    let sibling = ConnectionDocument {
        connection_id: other_connection(),
        organization: other_organization(),
        // No link: the configuration is refused before any login, so a link on the sibling
        // would decide nothing and would assert a principal this case does not need.
        linked: false,
        ..ConnectionDocument::accepted(&issuer)
    };
    let case = "tenant-ambiguous";
    let paths: Vec<PathBuf> = [selected.rendered(), sibling.rendered()]
        .iter()
        .enumerate()
        .map(|(nth, body)| document(case, &format!("connection-{nth}.json"), body))
        .collect();
    let key_path = document(case, "key.json", AS_KEY_DOCUMENT);

    let refused = Command::new(env!("CARGO_BIN_EXE_mandate-control-plane"))
        .args([
            "serve",
            "--listen",
            "127.0.0.1:0",
            "--issuer",
            AS_ISSUER,
            "--connection",
            stated(&paths[0]),
            "--connection",
            stated(&paths[1]),
            "--key",
            stated(&key_path),
        ])
        .output()
        .expect("the composition binary runs");

    assert_eq!(
        refused.status.code(),
        Some(2),
        "a configuration whose logins would all be ambiguous is the operator's to correct; \
         it said {}",
        String::from_utf8_lossy(&refused.stderr)
    );
    let said = String::from_utf8_lossy(&refused.stderr);
    assert!(
        said.contains("TenantResolutionUnadmitted"),
        "the clause the registration command states for this pair, got {said}"
    );
    assert!(
        said.contains(stated(&paths[1])),
        "the refusal names the document it could not admit, got {said}"
    );
}

/// The configuration step: a `--connection` document omitting `algorithm`.
///
/// `RealVerifier` refuses to have a default at all — `jsonwebtoken`'s own would be `HS256`
/// — and a connection no algorithm was configured for verifies nothing
/// (`RefusalReason::ConnectionAlgorithmUnconfigured`). The proof this case presents is the
/// one the accepted case's connection admits, so a deployment that defaulted to the
/// signed-with algorithm would answer `200` here.
#[test]
fn a_connection_configured_for_no_algorithm_refuses_rather_than_defaulting() {
    let signer = idp_signer();
    let jwks = serde_json::to_string(&signer.published_keys()).expect("the published key set");
    let issuer = issuer_publishing(jwks);

    let unconfigured = ConnectionDocument {
        algorithm: None,
        ..ConnectionDocument::accepted(&issuer)
    };
    let (address, mut served) = stand_up("no-algorithm", &[unconfigured.rendered()]);

    let proof = proof_from(&signer, &issuer, IDP_CLIENT, "proof-algorithm");
    let login = login_with(address, connection(), &proof);
    refused(
        "configuration (no algorithm): POST /v1/federation/login",
        &login,
        400,
        &denied_body("access_denied"),
    );

    // The child bound its listener and seeded the connection, so the document was read and
    // accepted: this is a login refused at the verifier, not a configuration the binary
    // rejected at startup — which would have been an exit status and no response at all.
    // `AlgorithmPolicy` is the clause and the absent configuration is the reason, which is
    // what an expired proof on this same connection would not produce.
    refusal_taken(
        &mut served,
        LOGIN,
        "AlgorithmPolicy",
        Some("ConnectionAlgorithmUnconfigured"),
        &[connection()],
    );
}

/// Step 7, resolve the external principal: a proof this connection has no link for, on a
/// connection that does not admit provisioning.
///
/// `federation.yaml:4` gives `jit_provisioning` one meaning — a connection that does not
/// admit provisioning "denies the first login and creates nothing" — and
/// `Deployment::authenticate` reads the flag only after the login has already refused
/// `LinkAbsent`. Every earlier step passes here: the proof is the accepted one.
#[test]
fn a_first_login_a_connection_does_not_admit_provisioning_for_is_refused_at_step_seven() {
    let signer = idp_signer();
    let jwks = serde_json::to_string(&signer.published_keys()).expect("the published key set");
    let issuer = issuer_publishing(jwks);

    let unlinked = ConnectionDocument {
        linked: false,
        jit_provisioning: false,
        ..ConnectionDocument::accepted(&issuer)
    };
    let (address, mut served) = stand_up("link-absent", &[unlinked.rendered()]);

    let proof = proof_from(&signer, &issuer, IDP_CLIENT, "proof-link-absent");
    let login = login_with(address, connection(), &proof);
    refused(
        "step 7 link: POST /v1/federation/login",
        &login,
        400,
        &denied_body("access_denied"),
    );

    // The verifier refused nothing — the proof is valid and every step before this one
    // passed — so the record names the link and only the link.
    refusal_taken(&mut served, LOGIN, "LinkAbsent", None, &[connection()]);
}

/// Step 7 again, on the accepted side: the same first login, on a connection that **does**
/// admit provisioning, creates the principal and opens a session.
///
/// The two cases differ in one Boolean of one document. That is what makes the refusal
/// above a property of `jit_provisioning` rather than of anything else in the
/// configuration, and it is the only assertion in this file that the composition
/// `Deployment::authenticate` performs — authenticate, provision, authenticate again —
/// runs in the served binary at all.
#[test]
fn a_first_login_a_connection_admits_provisioning_for_opens_a_session_at_step_seven() {
    let signer = idp_signer();
    let jwks = serde_json::to_string(&signer.published_keys()).expect("the published key set");
    let issuer = issuer_publishing(jwks);

    let provisioning = ConnectionDocument {
        linked: false,
        jit_provisioning: true,
        ..ConnectionDocument::accepted(&issuer)
    };
    let (address, mut served) = stand_up("jit-login", &[provisioning.rendered()]);

    let proof = proof_from(&signer, &issuer, IDP_CLIENT, "proof-jit");
    let login = login_with(address, connection(), &proof);
    answered("step 7 jit: POST /v1/federation/login", &login);
    assert_eq!(
        login.status, 200,
        "a connection that admits provisioning opens the first login's session; got {} {}",
        login.status, login.body
    );
    assert!(
        !member(&login.body, "session_id").is_empty(),
        "the declared `session_id` response, got {}",
        login.body
    );
    // The principal is the one provisioning created, not the one the accepted case's
    // document names: no link was seeded, so this identity was minted by the child.
    assert_ne!(
        member(&login.body, "principal_id"),
        principal().to_string(),
        "a provisioned principal is not the seeded one; got {}",
        login.body
    );
    assert_eq!(
        member(&login.body, "organization_id"),
        organization().to_string(),
        "the session is opened in the connection's organization; got {}",
        login.body
    );

    // Nothing was refused on the way. The composition refuses `LinkAbsent` internally on
    // its first attempt and retries; that refusal is never rendered, so the child records
    // none — which is what distinguishes this from the case above.
    no_refusal_taken(&mut served, &[connection()]);
}
