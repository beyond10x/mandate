/// A client registered by the real handler, and the fold that holds it.
fn a_registered_client(organization_id: OrganizationId) -> (Projection, OAuthClientId) {
    let admission = ConfiguredAdmission::new()
        .with_administrator(administrator())
        .with_organization(organization_id)
        .with_redirect_uri(organization_id, redirect(REGISTERED));
    let mut allocator = SequentialAllocator::new();
    let registered = register_o_auth_client(
        &RegisterOAuthClient {
            context: context(organization_id),
            public: true,
            redirect_uris: vec![redirect(REGISTERED)],
            pkce_method: PkceMethod::S256,
        },
        &admission,
        &mut allocator,
    )
    .expect("the admission holds the caller, the organization and the redirect");

    (
        Projection::fold(&[registered.event]).expect("one registration"),
        registered.id,
    )
}

/// "the client is outside the verified organization".
#[test]
fn a_client_outside_the_verified_organization_is_refused_at_disable() {
    let (held, client_id) = a_registered_client(organization(10));

    let denied = disable_oauth_client(
        &DisableOAuthClient {
            context: context(organization(11)),
            id: client_id,
        },
        &held,
    )
    .expect_err("the client belongs to organization 10");

    assert_eq!(denied.reason, DenialReason::TenantMismatch);
    assert_eq!(denied.clause, DenialClause::OrganizationMismatch);
}

