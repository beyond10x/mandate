/// "tenant resolution has zero or multiple matches": multiple. Two configured tenants stand
/// behind one issuer and the proof matches both, so the first login resolves neither.
///
/// The writer refuses a second organization's rule a proof could satisfy alongside a held
/// one, so no single registration against a current fold reaches this pair. Two routes
/// still do, and the fold does not re-decide the guard on either. A replayed history: an
/// event log written before the guard refused different-claim rules folds through
/// `Projection::apply` as it was accepted (`Deployment::record_federation` in
/// `services/control-plane` is that raw fold; its
/// `serve.rs::two_connections_on_one_issuer_from_a_log_are_still_refused_as_ambiguous` holds
/// the pair that way). And the race the guard's own comment names: the guard is
/// read-then-write, so two registrations that each read the issuer before the other's event
/// is folded are both admitted. This case takes the second route, so both connections come
/// out of `register_federation_connection` rather than being folded by hand. Each
/// organization keys on the claim it uses — `{org: acme}` and `{dept: eng}` — and one proof
/// carrying both claims matches both rules.
#[test]
fn a_proof_matching_two_configured_tenants_is_refused_at_provisioning() {
    let mut allocator = SequentialAllocator::new();
    let unheld = Projection::default();
    let incumbent = register(organization(10), "org", "acme", &unheld, &mut allocator);
    let second = register(organization(11), "dept", "eng", &unheld, &mut allocator);
    let held =
        Projection::fold(&[incumbent.event, second.event]).expect("two connections on one issuer");
    let signing = keys("2026-09");
    let source = InMemoryJwks::new();
    source.publish(&Issuer::new(ISSUER_ONE), key_set(&[&signing]));
    let verifier = verifier(
        &source,
        &FixedClock::at(NOW),
        &[incumbent.connection_id, second.connection_id],
    );

    let denied = provision(
        &held,
        incumbent.connection_id,
        &verifier,
        mint(
            &signing,
            &with(
                with(claims(ISSUER_ONE, SUBJECT), "org", "acme".into()),
                "dept",
                "eng".into(),
            ),
        ),
    );

    assert_eq!(denied.reason, DenialReason::TenantMismatch);
    assert_eq!(denied.clause, DenialClause::TenantAmbiguous);
}

/// "the composite (organization, configured issuer, subject) key already exists": the first
/// login already happened, and provisioning creates nothing on top of it.
#[test]
fn a_subject_already_holding_the_composite_key_is_refused_at_provisioning() {
    let (signing, verifier) = published();
    let held = Projection::fold(&[
        created(
            connection(1),
            organization(10),
            ISSUER_ONE,
            unconditional(organization(10)),
            true,
        ),
        linked(connection(1), organization(10), SUBJECT, principal(0x21)),
    ])
    .expect("a connection and a link");

    let denied = provision(
        &held,
        connection(1),
        &verifier,
        mint(&signing, &claims(ISSUER_ONE, SUBJECT)),
    );

    assert_eq!(denied.reason, DenialReason::Denied);
    assert_eq!(denied.clause, DenialClause::ExternalKeyExists);
}

/// "any email-domain/unverified-input fallback would be required": the issuer signed the
/// address and did not assert it had verified it, so the rule that would have matched on it
/// refuses the request rather than resolving one.
#[test]
fn an_unverified_claim_a_tenant_rule_would_have_matched_is_refused_at_provisioning() {
    let (signing, verifier) = published();
    let held = Projection::fold(&[created(
        connection(1),
        organization(10),
        ISSUER_ONE,
        on_claim(organization(10), "email", "person@acme.example"),
        true,
    )])
    .expect("one connection");

    let denied = provision(
        &held,
        connection(1),
        &verifier,
        mint(
            &signing,
            &with(
                claims(ISSUER_ONE, SUBJECT),
                "email",
                "person@acme.example".into(),
            ),
        ),
    );

    assert_eq!(denied.reason, DenialReason::TenantMismatch);
    assert_eq!(
        denied.clause,
        DenialClause::UnverifiedFallback,
        "an address without `email_verified` is not a validated claim"
    );
}
