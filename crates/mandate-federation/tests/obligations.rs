/// The instant every case is dated from, as seconds since the Unix epoch.
const NOW: u64 = 1_758_240_000;

// ------------------------------------------------------------------ identities

fn uuid(tag: u8) -> Uuid {
    Uuid::from_bytes([tag; 16])
}

fn organization(tag: u8) -> OrganizationId {
    OrganizationId::new(uuid(tag))
}

fn connection(tag: u8) -> FederationConnectionId {
    FederationConnectionId::new(uuid(tag))
}

fn principal(tag: u8) -> PrincipalId {
    PrincipalId::new(uuid(tag))
}

fn external_principal(tag: u8) -> ExternalPrincipalId {
    ExternalPrincipalId::new(uuid(tag))
}

/// The caller the client-registration admission holds authority for.
fn administrator() -> PrincipalId {
    principal(0x51)
}

fn redirect(text: &str) -> RedirectUri {
    RedirectUri::new(text)
}

fn context(organization_id: OrganizationId) -> VerifiedContext {
    VerifiedContext {
        subject: administrator(),
        actor: None,
        organization: organization_id,
        audience: Audience::new("mandate"),
        credential: CredentialId::new(uuid(0xcd)),
        delegation: None,
        execution: None,
        correlation: CorrelationId::new("obligations-federation"),
    }
}

fn at() -> Timestamp {
    Timestamp::new("2026-09-18T00:00:00Z")
}

fn request() -> RequestContext {
    RequestContext {
        audience: Audience::new("mandate"),
        correlation: CorrelationId::new("obligations-federation"),
        credential: CredentialId::new(uuid(0xcd)),
        at: at(),
    }
}

// ---------------------------------------------------------------- the records

fn unconditional(organization_id: OrganizationId) -> TenantResolutionRule {
    TenantResolutionRule {
        configured_organization: organization_id,
        verified_claim_name: None,
        verified_claim_value: None,
    }
}

fn on_claim(organization_id: OrganizationId, name: &str, value: &str) -> TenantResolutionRule {
    TenantResolutionRule {
        configured_organization: organization_id,
        verified_claim_name: Some(name.to_owned()),
        verified_claim_value: Some(value.to_owned()),
    }
}

/// A registration of `ISSUER_ONE` for `organization_id`, keyed on one claim, as
/// `mandate.federation.RegisterFederationConnection` declares it.
fn registration(
    organization_id: OrganizationId,
    name: &str,
    value: &str,
) -> RegisterFederationConnection {
    RegisterFederationConnection {
        context: context(organization_id),
        issuer: Issuer::new(ISSUER_ONE),
        client_id: ClientId::new(CLIENT),
        tenant_resolution: on_claim(organization_id, name, value),
        jit_provisioning: true,
    }
}

/// Register one connection through the shipped writer, refusing to proceed on a denial:
/// an arrangement this command does not accept is not a state a deployment can reach.
fn register(
    organization_id: OrganizationId,
    name: &str,
    value: &str,
    held: &Projection,
    allocator: &mut SequentialAllocator,
) -> ConnectionRegistered {
    register_federation_connection(&registration(organization_id, name, value), held, allocator)
        .expect("the shipped writer admits this registration")
}

fn created(
    connection_id: FederationConnectionId,
    organization_id: OrganizationId,
    issuer: &str,
    tenant_resolution: TenantResolutionRule,
    jit_provisioning: bool,
) -> FederationEvent {
    FederationEvent::FederationConnectionCreated {
        context: context(organization_id),
        connection_id,
        issuer: Issuer::new(issuer),
        client_id: ClientId::new(CLIENT),
        tenant_resolution,
        jit_provisioning,
    }
}

fn linked(
    connection_id: FederationConnectionId,
    organization_id: OrganizationId,
    subject: &str,
    principal_id: PrincipalId,
) -> FederationEvent {
    FederationEvent::ExternalPrincipalLinked {
        context: context(organization_id),
        connection_id,
        principal_id,
        external_principal_id: external_principal(0x71),
        subject: ExternalSubject::new(subject),
        link_method: ExternalLinkMethod::Administrator,
        linked_at: at(),
    }
}

fn disabled(
    connection_id: FederationConnectionId,
    organization_id: OrganizationId,
) -> FederationEvent {
    FederationEvent::FederationConnectionDisabled {
        context: context(organization_id),
        id: connection_id,
    }
}

/// One enabled connection of organization 10 on `ISSUER_ONE`, admitting provisioning.
fn one_connection() -> Projection {
    Projection::fold(&[created(
        connection(1),
        organization(10),
        ISSUER_ONE,
        unconditional(organization(10)),
        true,
    )])
    .expect("one connection")
}

// ---------------------------------------------------------------- key material

/// A generated key pair, the public JWK that publishes it, and the `kid` it is published
/// under. Nothing is read from the repository: the key is generated when the case runs.
struct Keys {
    signing: EncodingKey,
    published: Jwk,
    kid: String,
}

/// A fresh P-256 key pair published under `kid`.
fn keys(kid: &str) -> Keys {
    let pkcs8 =
        EcdsaKeyPair::generate_pkcs8(&ECDSA_P256_SHA256_FIXED_SIGNING, &SystemRandom::new())
            .expect("a generated elliptic-curve key");
    let signing = EncodingKey::from_ec_der(pkcs8.as_ref());
    let mut published = Jwk::from_encoding_key(&signing, Algorithm::ES256).expect("a public JWK");
    published.common.key_id = Some(kid.to_owned());
    Keys {
        signing,
        published,
        kid: kid.to_owned(),
    }
}

fn key_set(published: &[&Keys]) -> serde_json::Value {
    serde_json::json!({
        "keys": published
            .iter()
            .map(|keys| serde_json::to_value(&keys.published).expect("a serializable JWK"))
            .collect::<Vec<_>>(),
    })
}

fn claims(issuer: &str, subject: &str) -> serde_json::Value {
    serde_json::json!({
        "iss": issuer,
        "sub": subject,
        "aud": CLIENT,
        "iat": NOW,
        "exp": NOW + 300,
    })
}

fn with(mut claims: serde_json::Value, name: &str, value: serde_json::Value) -> serde_json::Value {
    claims
        .as_object_mut()
        .expect("a claims object")
        .insert(name.to_owned(), value);
    claims
}

fn mint(keys: &Keys, claims: &serde_json::Value) -> CredentialProof {
    let mut header = Header::new(Algorithm::ES256);
    header.kid = Some(keys.kid.clone());
    let token = encode(&header, claims, &keys.signing).expect("a signed token");
    CredentialProof::from_bytes(token.into_bytes())
}

/// The real verifier over a published key set, a fixed clock and the connections whose
/// algorithm the deployment configured.
fn verifier(
    source: &InMemoryJwks,
    clock: &FixedClock,
    configured: &[FederationConnectionId],
) -> RealVerifier<InMemoryJwks, FixedClock> {
    let allowed = AllowedAlgorithms::configured(&[SigningAlgorithm::new(ES256)])
        .expect("a non-empty allowlist is admitted");
    let mut built = RealVerifier::new(allowed, source.clone(), clock.clone());
    for connection_id in configured {
        built = built
            .configure_connection(*connection_id, &SigningAlgorithm::new(ES256))
            .expect("an admitted algorithm for this connection");
    }
    built
}

/// One published issuer, its verifier, and the key that signs for it.
fn published() -> (Keys, RealVerifier<InMemoryJwks, FixedClock>) {
    let signing = keys("2026-09");
    let source = InMemoryJwks::new();
    source.publish(&Issuer::new(ISSUER_ONE), key_set(&[&signing]));
    let verifier = verifier(&source, &FixedClock::at(NOW), &[connection(1)]);
    (signing, verifier)
}

/// `ProvisionExternalPrincipal` against the real handler.
fn provision(
    projection: &Projection,
    connection_id: FederationConnectionId,
    verifier: &RealVerifier<InMemoryJwks, FixedClock>,
    proof: CredentialProof,
) -> Denied {
    let mut allocator = SequentialAllocator::new();
    provision_external_principal(
        &ProvisionExternalPrincipal {
            connection_id,
            proof,
        },
        &request(),
        verifier,
        projection,
        projection,
        &mut allocator,
    )
    .expect_err("this case is a refusal")
}

