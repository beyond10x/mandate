/// "proof signature/issuer/audience/expiry is invalid": the expiry half.
#[test]
fn a_proof_whose_expiry_has_passed_is_refused_at_provisioning() {
    let signing = keys("2026-09");
    let source = InMemoryJwks::new();
    source.publish(&Issuer::new(ISSUER_ONE), key_set(&[&signing]));
    // The token is minted inside its window and presented after it: the clock the request
    // is served under is past the `exp` the issuer signed.
    let verifier = verifier(&source, &FixedClock::at(NOW + 600), &[connection(1)]);

    let denied = provision(
        &one_connection(),
        connection(1),
        &verifier,
        mint(&signing, &claims(ISSUER_ONE, SUBJECT)),
    );

    assert_eq!(denied.reason, DenialReason::InvalidCredential);
    assert_eq!(denied.clause, DenialClause::ProofInvalid);
}

