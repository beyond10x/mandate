//! The denial clauses of `mandate.federation` that `contracts/obligations/federation.json`
//! carried unbound, each driven to exactly the clause it names.
//!
//! `story:obligation-registry` split every implemented command's declared `condition.cause`
//! into its clauses and bound the ones an existing case already decided. Twenty were left
//! `blocked_on: story:obligations-federation`, which is this file. Sixteen are decided here:
//! thirteen refuse through the handler the crate ships, with no stand-in deciding anything,
//! and the three of `mandate.federation.RegisterOAuthClient` are decided by the
//! `ClientRegistrationAdmission` implementation they are passed, which is why the document
//! publishes those three on the `double` path (*Where a double decides*, below). Every case
//! asserts both halves of the refusal: the contract's `mandate.core.DenialReason` and the
//! crate-local [`DenialClause`] that says *which* declared condition fired. Asserting the
//! reason alone would let a clause be satisfied by any refusal of the command.
//!
//! # Why the verifier here is the real one
//!
//! `story:signing-and-verification` shipped [`RealVerifier`], so the proof-driven cases mint
//! a real token with a key generated in this process and verify it through the same code a
//! deployment runs. [`mandate_federation::verifier::ConstructedVerifier`] admits or refuses
//! by construction: a proof clause it "decided" would be evidence about the double and not
//! about the shipped path, which is exactly what `contracts/obligations/README.md` counts in
//! its own column. [`InMemoryJwks`] publishes the key set and [`FixedClock`] dates the
//! request; neither decides a refusal — they supply what the verifier reads, and a key set
//! and a clock are the deployment's input in production too.
//!
//! Every key is generated by `aws_lc_rs` when the case runs, under ES256: no private key is
//! read from the repository and nothing here opens a socket.
//!
//! # Where a double decides
//!
//! The three `mandate.federation.RegisterOAuthClient` cases are the exception, and
//! `contracts/obligations/federation.json` publishes them as one: each row is
//! `path: "double"`, `double: "mandate_federation::register_client::ConfiguredAdmission"`,
//! and each clause carries `blocked_on: "decision-blocker:guards"`.
//!
//! `register_client.rs:93` declares a port, not a decision. The handler compares nothing: it
//! asks `ClientRegistrationAdmission` the three questions the declared denial names and turns
//! a `false` into the refusal, so what refuses is the implementation it was handed. The only
//! implementation in this workspace is [`ConfiguredAdmission`], which `register_client.rs:181`
//! calls "a fixture, never a shipped implementation" and which
//! `crates/mandate-conformance/src/external.rs:248` registers as this port's standing double,
//! beside `mandate_graph::double::GraphDouble` and `mandate_policy::double::PolicyDouble`
//! whose clauses are published the same way. By `contracts/obligations/README.md` that is a
//! `double` row: it is counted in `double_only`, it never covers, and it carries a
//! `blocked_on` naming what owns the port's shipped implementation rather than this file —
//! the shipped client-administration adapter is what `decision-blocker:guards` owns.
//!
//! The three cases stay, because a double row is evidence of exactly what it says: the
//! handler reaches the port for each of the three conditions and reports the
//! [`DenialClause`] the port's answer selects, which is what binds the clause to a condition
//! rather than to "the command refused".
//!
//! # What is not here
//!
//! Nine clauses of this crate's commands stay deferred, and none of them for want of a case.
//! Four name an administration authority the handler deciding them takes no admission port
//! for at all, which is `story:federation-admission-port`; `register_client.rs:93` is where
//! that port exists, and it decides nothing itself — the answer is the implementation's, and
//! today the only one is the fixture [`ConfiguredAdmission`] (above). The durable-commit and
//! invalidation clauses name the adapter's transaction. Two more — "STS code
//! issuance/narrowing is refused" and "disablement cannot stop the issuance of new
//! authorization codes to it" — are decided by `mandate-sts` code no case in this crate
//! reaches, which is `story:cross-crate-clauses`. `contracts/obligations/federation.json`
//! records which story or blocker owns each of those paths.

