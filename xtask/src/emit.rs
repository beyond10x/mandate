//! The contract's Rust shapes, emitted from the compiled model.
//!
//! ESS 0.26.0 realizes Rust for type roots only, so the three kinds a Mandate reader actually
//! holds — the event payload, the command input and response, the entity record — have no
//! generated shape and nothing binds a hand-written one to its declaration. This module emits
//! them, deterministically, from `generated/ir/system.json`: the same bytes `cargo xtask
//! contracts` byte-compares, so a shape that drifts from its declaration is a failing gate.
//!
//! The emission is a pure function of those bytes. There is no clock in it, no environment and
//! no hash-order iteration — every index is walked through a `BTreeMap` — because the whole
//! value of the byte-compare is that a second emission of the same model is the same file.
//!
//! # What ESS 0.26.0's own realizer does differently
//!
//! `ess generate types --target rust` reads a JSON Schema, not the compiled model, and its
//! output is not this output renamed. At tag 0.26.0
//! (`crates/generate/schema-contract/src/realize/rust.rs`) it:
//!
//! - admits **type roots only**, which is why the three kinds above are emitted here at all;
//! - writes **one file**, `types.rs`, with its own `Cargo.toml` on edition 2021, against this
//!   emitter's four modules inside the workspace;
//! - names every enum variant **positionally** — `V0`, `V1`, … carrying `#[serde(rename)]` —
//!   where this emitter uses the declared variant name, so an ESS-realized enum is a different
//!   Rust API for the same wire values;
//! - encodes a union as `#[serde(untagged)]` with a hand-written `Deserialize` that takes the
//!   **first structurally decodable** alternative, where this emitter encodes the union
//!   adjacently, under the tag the IR declares. The content key is not declared anywhere: the
//!   IR's union body carries a tag and nothing else, and `value` is this emitter's own
//!   literal, chosen because ESS's JSON Schema projection spells every branch as an object of
//!   exactly `{<tag>, value}`. If that projection ever spells it differently, this literal is
//!   the line that has to move;
//! - carries absence as `EssPresence<T>`, whose `Deserialize` delegates straight to `T` — so
//!   `null` is refused only when `T` happens to refuse it, where [`PRESENCE`] refuses `null`
//!   itself, in every position, by name;
//! - stamps `// @generated by ESS <version>` and a source digest rather than this header.
//!
//! Its `EssPresence::Absent` does refuse to serialize, and this emitter follows it exactly.
//!
//! # Retirement
//!
//! Retiring this emitter is not a promise that ESS will one day write these bytes: the two
//! outputs differ in the API they present, and the paragraph above is the list. It is a
//! measurement — when the realizer admits events, commands and entities, emit both and
//! byte-compare the realizer's output against this one, and let the diff decide what is a
//! Mandate decision worth keeping and what was only this emitter's habit. Until that diff has
//! been read, nothing here may be deleted on the assumption that ESS agrees.

