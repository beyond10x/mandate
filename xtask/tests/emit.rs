#[test]
fn two_emissions_of_one_model_are_byte_identical() {
    let model = model();
    let first = emit::render(&model).expect("first emission");
    let second = emit::render(&model).expect("second emission");
    assert_eq!(first, second);
}

#[test]
fn the_four_files_are_emitted_and_each_starts_with_the_digest_of_the_model_it_read() {
    let files = rendered();
    assert_eq!(
        files.keys().collect::<Vec<_>>(),
        ["commands.rs", "entities.rs", "events.rs", "types.rs"]
            .iter()
            .collect::<Vec<_>>()
    );
    let digest = emit::digest(&model());
    let header = format!(
        "// Generated by cargo xtask generate from ir/system.json (sha256 {digest}) \
         with ess 0.26.0. Do not edit.\n"
    );
    for (name, body) in &files {
        assert!(body.starts_with(&header), "{name} has no header line");
    }
}

#[test]
fn a_changed_model_changes_the_digest_every_file_carries() {
    let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
    model["summary"] = Value::String("doctored".to_owned());
    let doctored = serde_json::to_vec(&model).expect("serialize");
    let before = emit::digest(&self::model());
    let after = emit::digest(&doctored);
    assert_ne!(before, after);
    for body in emit::render(&doctored).expect("emission").values() {
        assert!(body.contains(&after));
        assert!(!body.contains(&before));
    }
}

/// Every element of the four emitted kinds is declared once, and nothing else is.
///
/// The expectation is the IR's own index, not a number: a set equality states both halves —
/// no element is missing and no declaration is invented — and stays true as the contract grows.
/// The counts are asserted beside it as the figure this wave measured.
#[test]
fn every_element_the_model_declares_is_emitted_exactly_once() {
    let files = rendered();
    let model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");

    let states = model["entities"]
        .as_object()
        .expect("entities")
        .values()
        .map(|entity| emit::declaration_name(entity["state_type"].as_str().expect("a state type")))
        .collect::<BTreeSet<_>>();

    for (file, expected) in [
        (
            "types.rs",
            names(&model, "types", "")
                .difference(&states)
                .cloned()
                .chain(["Presence".to_owned()])
                .collect::<BTreeSet<_>>(),
        ),
        (
            "entities.rs",
            names(&model, "entities", "")
                .union(&states)
                .cloned()
                .collect(),
        ),
        ("events.rs", names(&model, "events", "")),
        (
            "commands.rs",
            names(&model, "commands", "Input")
                .union(&names(&model, "errors", ""))
                .cloned()
                .chain(
                    model["commands"]
                        .as_object()
                        .expect("commands")
                        .iter()
                        .filter(|(_, command)| command.get("response").is_some())
                        .map(|(name, _)| format!("{}Response", emit::declaration_name(name))),
                )
                .collect(),
        ),
    ] {
        let emitted = declarations(&files[file]);
        let once = emitted.iter().cloned().collect::<BTreeSet<_>>();
        assert_eq!(once.len(), emitted.len(), "{file} declares a name twice");
        assert_eq!(
            once, expected,
            "{file} does not declare what the IR carries"
        );
    }

    // The figures this wave measured, so a silently shrinking emission is a failure here too.
    assert_eq!(declarations(&files["events.rs"]).len(), 74);
    assert_eq!(declarations(&files["entities.rs"]).len(), 72); // 36 entities and 36 state enums
    assert_eq!(declarations(&files["commands.rs"]).len(), 98); // 61 inputs, 26 responses, 11 errors
    assert_eq!(declarations(&files["types.rs"]).len(), 75); // 110 types less 36 states, and Presence
}

/// A response is emitted for the command that declares one, and only for it.
///
/// 35 of the 61 commands carry no `response` key at all. An emitter that answered them with an
/// empty record would be inventing a declaration the contract does not make, and every reader
/// of the crate would then take the silence for a shape.
#[test]
fn only_a_command_that_declares_a_response_is_given_one() {
    let files = rendered();
    let model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
    let commands = model["commands"].as_object().expect("commands");
    let declared = commands
        .values()
        .filter(|command| command.get("response").is_some())
        .count();
    assert_eq!(declared, 26);
    assert_eq!(
        declarations(&files["commands.rs"])
            .iter()
            .filter(|name| name.ends_with("Response"))
            .count(),
        declared
    );
    assert!(files["commands.rs"].contains("pub struct MandateAuditRecordAuditEventResponse {"));
    assert!(!files["commands.rs"].contains("MandateAuditRedactAuditEventResponse"));
}

#[test]
fn an_event_that_reaches_credential_material_is_refused_by_name() {
    for secret in [
        "mandate.core.CredentialSecret",
        "mandate.core.CredentialProof",
    ] {
        let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
        model["events"]["mandate.identity.SessionRevoked"]["fields"]
            .as_array_mut()
            .expect("event fields")
            .push(serde_json::json!({
                "name": "secret",
                "type_ref": {"kind": "declared", "name": secret},
                "naming": {}
            }));
        let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
            .expect_err("an event carrying credential material is refused")
            .to_string();
        assert!(
            refusal.contains("mandate.identity.SessionRevoked"),
            "{refusal}"
        );
        assert!(refusal.contains(secret), "{refusal}");
        assert!(refusal.contains("secret"), "{refusal}");
    }
}

/// The refusal follows the reference graph, not just the field's own type.
///
/// A declaration reaches credential material through any chain of declared types, and the one
/// that matters is the indirect one: a field typed `VerifiedContext` looks harmless at the
/// event and carries the secret two hops down.
#[test]
fn an_entity_that_reaches_credential_material_indirectly_is_refused_with_the_path() {
    let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
    model["types"]["mandate.core.VerifiedContext"]["body"]["fields"]
        .as_array_mut()
        .expect("struct fields")
        .push(serde_json::json!({
            "name": "proof",
            "type_ref": {"kind": "declared", "name": "mandate.core.CredentialProof"},
            "naming": {}
        }));
    model["entities"]["mandate.identity.Principal"]["fields"]
        .as_array_mut()
        .expect("entity fields")
        .push(serde_json::json!({
            "name": "opened_with",
            "type_ref": {"kind": "declared", "name": "mandate.core.VerifiedContext"},
            "naming": {}
        }));
    let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
        .expect_err("an entity reaching credential material is refused")
        .to_string();
    assert!(refusal.contains("mandate.identity.Principal"), "{refusal}");
    assert!(
        refusal.contains("mandate.core.VerifiedContext -> mandate.core.CredentialProof"),
        "{refusal}"
    );
}

/// A command input may carry credential material, and seven of them do.
///
/// The refusal is about the record: an event is the durable one and an entity is the projected
/// one, and neither may hold a secret. A command input is the message that carries the
/// credential to be verified, so refusing it would refuse the contract as declared.
#[test]
fn a_command_input_may_carry_credential_material() {
    let files = rendered();
    assert!(files["commands.rs"].contains("MandateCoreCredentialSecret"));
    assert!(files["commands.rs"].contains("MandateCoreCredentialProof"));
    assert!(!files["events.rs"].contains("MandateCoreCredentialSecret"));
    assert!(!files["events.rs"].contains("MandateCoreCredentialProof"));
    assert!(!files["entities.rs"].contains("MandateCoreCredentialSecret"));
    assert!(!files["entities.rs"].contains("MandateCoreCredentialProof"));
}

