//! The emitter's cases, decided against the committed IR and doctored copies of it.
//!
//! Every case reads `generated/ir/system.json` — the same bytes `cargo xtask generate` reads —
//! so what is proved here is proved about the emission the gate byte-compares. The doctored
//! cases copy that model and change one declaration, which is the only way to reach a refusal
//! the contract does not currently provoke.
#[allow(dead_code)] // the binary target uses the whole module; a case here uses part of it.
#[path = "../src/emit.rs"]
mod emit;

use serde_json::Value;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Path, PathBuf},
};

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("workspace root")
        .to_owned()
}

/// The committed model: the emitter's only input.
fn model() -> Vec<u8> {
    fs::read(repo().join("generated/ir/system.json")).expect("the committed IR")
}

fn rendered() -> BTreeMap<String, String> {
    emit::render(&model()).expect("the committed IR emits")
}

/// Every declaration a file introduces, by Rust name.
///
/// Only a line that starts a declaration at column zero counts, so the `Declared` visitor
/// nested inside `Presence`'s `Deserialize` impl is not one of them — it is indented and
/// private, and neither is true of an emitted declaration.
fn declarations(body: &str) -> Vec<String> {
    body.lines()
        .filter_map(|line| {
            line.strip_prefix("pub struct ")
                .or_else(|| line.strip_prefix("pub enum "))
        })
        .map(|rest| {
            rest.split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
                .next()
                .unwrap_or_default()
                .to_owned()
        })
        .collect()
}

/// The names the IR declares for one kind, projected through the naming rule.
fn names(model: &Value, kind: &str, suffix: &str) -> BTreeSet<String> {
    model[kind]
        .as_object()
        .expect("an IR index")
        .keys()
        .map(|name| format!("{}{suffix}", emit::declaration_name(name)))
        .collect()
}

