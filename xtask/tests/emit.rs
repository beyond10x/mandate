/// Two declarations that become one Rust name are refused, naming both and the name.
///
/// The naming rule drops every character Rust cannot take, so it is not injective. ESS refuses
/// this itself; an emitter that reproduced the rule without the guard would answer with two
/// declarations of one name — and where the two land in different modules, with no answer.
#[test]
fn two_declarations_that_become_one_rust_name_are_refused() {
    for (kind, name, collides_with) in [
        ("types", "mandate.core.Space_Id", "mandate.core.SpaceId"),
        (
            "events",
            "mandate.identity.Session_Revoked",
            "mandate.identity.SessionRevoked",
        ),
    ] {
        let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
        let existing = model[kind][collides_with].clone();
        model[kind][name] = existing;
        let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
            .expect_err("a Rust name two declarations reach is refused")
            .to_string();
        assert!(refusal.contains(&emit::declaration_name(name)), "{refusal}");
        assert!(refusal.contains(name), "{refusal}");
        assert!(refusal.contains(collides_with), "{refusal}");
    }
}

