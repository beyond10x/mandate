/// An optional is a record key or it is refused, in every position the model can put one.
///
/// Absence is a property of a *key*. `Presence` can be skipped out of an object and read back
/// from a missing key, and it can do neither anywhere else: the contract's own JSON Schema
/// projection spells absence in a newtype as `null` (`anyOf: [$ref, {"type": "null"}]`), in a
/// union as a content key dropped from `required`, and in a list it has no spelling at all.
/// So the enumeration below is every position `positions()` reports that is not a record key,
/// and each one is a refusal naming the declaration that carries it.
#[test]
fn an_optional_is_a_record_key_or_it_is_refused() {
    let optional = serde_json::json!({
        "kind": "optional",
        "of": {"kind": "declared", "name": "mandate.core.SessionId"}
    });

    // Inside a list, on an event field and on an error field.
    for (kind, declaration) in [
        ("events", "mandate.identity.SessionRevoked"),
        ("errors", "mandate.audit.Denied"),
    ] {
        let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
        model[kind][declaration]["fields"]
            .as_array_mut()
            .expect("fields")
            .push(serde_json::json!({
                "name": "prior_ids",
                "type_ref": {"kind": "list", "of": optional.clone()},
                "naming": {}
            }));
        let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
            .expect_err("an optional inside a list is refused")
            .to_string();
        assert!(refusal.contains("prior_ids"), "{refusal}");
        assert!(refusal.contains(declaration), "{refusal}");
        assert!(refusal.contains("inside a list"), "{refusal}");
    }

    // A union variant.
    let mut variant: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
    variant["types"]["mandate.core.AuthoritySubject"]["body"]["variants"]["team"] =
        optional.clone();
    let refusal = emit::render(&serde_json::to_vec(&variant).expect("serialize"))
        .expect_err("an optional union variant is refused")
        .to_string();
    assert!(
        refusal.contains("mandate.core.AuthoritySubject"),
        "{refusal}"
    );
    assert!(refusal.contains("union variant"), "{refusal}");

    // The value a newtype wraps.
    let mut wrapped: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
    wrapped["types"]["mandate.core.Audience"]["body"]["of"] = optional.clone();
    let refusal = emit::render(&serde_json::to_vec(&wrapped).expect("serialize"))
        .expect_err("an optional newtype is refused")
        .to_string();
    assert!(refusal.contains("mandate.core.Audience"), "{refusal}");

    // An optional inside another optional, on a record key that may itself be optional.
    let mut nested: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
    nested["events"]["mandate.identity.SessionRevoked"]["fields"][0]["type_ref"] =
        serde_json::json!({"kind": "optional", "of": optional.clone()});
    let refusal = emit::render(&serde_json::to_vec(&nested).expect("serialize"))
        .expect_err("an optional inside an optional is refused")
        .to_string();
    assert!(
        refusal.contains("mandate.identity.SessionRevoked"),
        "{refusal}"
    );
    assert!(refusal.contains("inside another optional"), "{refusal}");

    // And the shipped model puts an optional only on record keys, so none of this fires on it.
    let files = rendered();
    for body in files.values() {
        assert!(
            !body.contains("Presence<Presence<"),
            "a nested optional was emitted"
        );
        assert!(
            !body.contains("Vec<Presence<"),
            "an optional list element was emitted"
        );
        assert!(
            !body.contains("(pub Presence<"),
            "an optional newtype was emitted"
        );
    }
}

/// Every refusal names the declaration that carries it, and the field inside it.
///
/// A refusal that names neither is reported against a generated file, and the whole point of
/// the emitter is that a contract defect is reported against the declaration. The two that did
/// not — an unmapped primitive and an unmapped type expression — are the last of the class.
#[test]
fn every_refusal_names_the_declaration_and_the_field() {
    for type_ref in [
        serde_json::json!({"kind": "primitive", "name": "decimal"}),
        serde_json::json!({"kind": "map", "of": {"kind": "primitive", "name": "string"}}),
        serde_json::json!({"kind": "declared", "name": "mandate.core.NotDeclared"}),
        serde_json::json!({
            "kind": "list",
            "of": {"kind": "optional", "of": {"kind": "declared", "name": "mandate.core.SessionId"}}
        }),
    ] {
        for (kind, declaration) in [
            ("events", "mandate.identity.SessionRevoked"),
            ("entities", "mandate.identity.Principal"),
            ("errors", "mandate.audit.Denied"),
        ] {
            let mut model: Value =
                serde_json::from_slice(&model()).expect("the committed IR parses");
            model[kind][declaration]["fields"]
                .as_array_mut()
                .expect("fields")
                .push(serde_json::json!({
                    "name": "rate",
                    "type_ref": type_ref.clone(),
                    "naming": {}
                }));
            let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
                .expect_err("the emitter refuses what it cannot map")
                .to_string();
            assert!(refusal.contains(declaration), "{type_ref}: {refusal}");
            assert!(refusal.contains("rate"), "{type_ref}: {refusal}");
        }
    }
}

/// An `integer` is `serde_json::Number`, because the schema's `integer` is not an `i64`.
///
/// `{"type": "integer"}` in JSON Schema 2020-12 is any number with a zero fractional part, and
/// the projection carries no range, so `1.0` and `2^63` are both documents the contract admits
/// and neither is an `i64`. This is ESS's own mapping for the same reason.
#[test]
fn an_integer_is_the_number_the_schema_admits() {
    let files = rendered();
    assert!(files["events.rs"].contains("pub generation: ::serde_json::Number,"));
    assert!(files["entities.rs"].contains("pub generation: ::serde_json::Number,"));
    assert!(!files["events.rs"].contains("i64"));
    assert!(!files["entities.rs"].contains("i64"));
    assert!(!files["commands.rs"].contains("i64"));
    assert!(!files["types.rs"].contains("i64"));
}
