/// A name Rust cannot take is a refusal, not broken source.
///
/// Every field name and enum variant in the model is a plain Rust identifier today. An
/// emitter that assumed it would stay that way would answer a renamed declaration with a file
/// that does not parse, and the failure would be reported against the crate rather than
/// against the declaration that caused it.
#[test]
fn a_name_rust_cannot_take_is_refused() {
    for (name, needle) in [
        ("type", "type"),
        ("session-id", "session-id"),
        // Reserved, not strict: `rustc --edition 2024` answers "expected identifier, found
        // reserved keyword" for each of these exactly as it does for a strict one.
        ("try", "try"),
        ("gen", "gen"),
        ("become", "become"),
        ("priv", "priv"),
        // The four that cannot even be raw identifiers, so escaping is not an answer.
        ("self", "self"),
        ("Self", "Self"),
        ("crate", "crate"),
        ("super", "super"),
    ] {
        let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
        model["events"]["mandate.identity.SessionRevoked"]["fields"]
            .as_array_mut()
            .expect("event fields")
            .push(serde_json::json!({
                "name": name,
                "type_ref": {"kind": "declared", "name": "mandate.core.SessionId"},
                "naming": {}
            }));
        let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
            .expect_err("a name Rust cannot take is refused")
            .to_string();
        assert!(refusal.contains(needle), "{refusal}");
        assert!(
            refusal.contains("mandate.identity.SessionRevoked"),
            "{refusal}"
        );
    }
}

