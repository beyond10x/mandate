///
/// The emitted record is the declared identity, the declared fields and an injected `state`.
/// A declared field named `state` — or named for the identity, `id` — would be the second key
/// of that name in one record, which serde answers with a compile error in a generated file.
#[test]
fn an_entity_field_that_collides_with_the_identity_or_the_state_is_refused() {
    for name in ["state", "id"] {
        let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
        model["entities"]["mandate.identity.Principal"]["fields"]
            .as_array_mut()
            .expect("entity fields")
            .push(serde_json::json!({
                "name": name,
                "type_ref": {"kind": "primitive", "name": "string"},
                "naming": {}
            }));
        let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
            .expect_err("a field the record already carries is refused")
            .to_string();
        assert!(refusal.contains(name), "{refusal}");
        assert!(refusal.contains("mandate.identity.Principal"), "{refusal}");
    }
}

