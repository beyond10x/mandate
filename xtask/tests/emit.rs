/// A declared reference the model does not carry is a refusal, in every position.
///
/// The class is "a name that resolves to nothing", and the emitter answers it the same way
/// wherever it sits: a struct field, a command input, a union variant, the value a newtype
/// wraps. The credential walk is listed here too, because that is the position where a silent
/// `None` would read as "this declaration holds no secret" rather than "this name is not one".
#[test]
fn a_declared_reference_the_model_does_not_carry_is_refused_everywhere() {
    let missing = serde_json::json!({"kind": "declared", "name": "mandate.core.NotDeclared"});
    for (path, position) in [
        (
            vec!["events", "mandate.identity.SessionRevoked", "fields", "0"],
            "context",
        ),
        (
            vec!["commands", "mandate.audit.RecordAuditEvent", "input", "0"],
            "emitter_context",
        ),
        (
            vec!["entities", "mandate.identity.Principal", "fields", "0"],
            "kind",
        ),
        (
            vec!["errors", "mandate.audit.Denied", "fields", "0"],
            "reason",
        ),
    ] {
        let mut model: Value = serde_json::from_slice(&model()).expect("the committed IR parses");
        let mut at = &mut model;
        for step in &path {
            at = match step.parse::<usize>() {
                Ok(index) => &mut at.as_array_mut().expect("an array")[index],
                Err(_) => &mut at[step],
            };
        }
        at["type_ref"] = missing.clone();
        let refusal = emit::render(&serde_json::to_vec(&model).expect("serialize"))
            .expect_err("a reference to nothing is refused")
            .to_string();
        assert!(refusal.contains("mandate.core.NotDeclared"), "{refusal}");
        assert!(refusal.contains(position), "{refusal}");
    }
}

